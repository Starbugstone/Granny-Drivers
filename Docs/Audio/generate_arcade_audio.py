"""Original deterministic mono PCM effects; run from any directory with Python 3."""
import math, random, wave, struct, json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'Assets/GrannyRacer/Audio/SFX/Arcade'
RATE=24000
rng=random.Random(2718)
TAU=math.tau

def tone(freq,t):return math.sin(TAU*freq*t)+.22*math.sin(TAU*freq*2*t)+.08*math.sin(TAU*freq*3*t)
def notes(seq,step):
    result=[]
    for freq in seq:
        for i in range(round(step*RATE)):
            t=i/RATE;env=min(1,t/.008)*max(0,1-t/step)**1.7
            result.append(tone(freq,t)*env)
    return result

def write(name,data,loop=False):
    dc=sum(data)/len(data);data=[v-dc for v in data]
    peak=max(abs(v) for v in data);data=[v/max(peak,1e-6)*.65 for v in data]
    if not loop:
        for i in range(min(240,len(data)//2)):
            data[i]*=i/240;data[-1-i]*=i/240
    with wave.open(str(OUT/(name+'.wav')),'wb') as f:
        f.setnchannels(1);f.setsampwidth(2);f.setframerate(RATE);f.writeframes(struct.pack('<'+'h'*len(data),*(round(v*32767) for v in data)))
    return {'clip':name,'seconds':len(data)/RATE,'peakDbFS':20*math.log10(max(abs(v) for v in data)),'rmsDbFS':20*math.log10(math.sqrt(sum(v*v for v in data)/len(data))),'loop':loop,'endpointDelta':abs(data[-1]-data[0])}

def main():
    OUT.mkdir(parents=True,exist_ok=True);report=[]
    for name,seq,step in [('Countdown',[440],.16),('Go',[523.25,659.25,783.99,1046.5],.085),('Gate',[783.99,1046.5],.065),('Lap',[659.25,783.99,1046.5],.13),('FinalLap',[523.25,783.99,1046.5,1174.66],.12),('Finish',[523.25,659.25,783.99,1046.5,783.99,1046.5],.19),('BoostBurst',[196,293.66,440,659.25],.055),('Burnout',[311.13,277.18,185,92.5],.11)]:report.append(write(name,notes(seq,step)))
    # Integer-frequency harmonics, including modulation, meet exactly at the one-second seam.
    for name,fn in [('Roll',lambda t:.5*math.sin(TAU*72*t)+.2*math.sin(TAU*144*t)+.12*math.sin(TAU*432*t)*(1+.5*math.sin(TAU*12*t))),('Skid',lambda t:math.sin(TAU*587*t+2*math.sin(TAU*17*t))*.55+.2*math.sin(TAU*881*t)),('Rocket',lambda t:.4*math.sin(TAU*96*t+3*math.sin(TAU*13*t))+.35*math.sin(TAU*192*t)+.1*math.sin(TAU*624*t)),('Garden',lambda t:.12*math.sin(TAU*84*t)+.25*math.sin(TAU*1900*t)*max(0,math.sin(TAU*2*t))**12)]:
        report.append(write(name,[fn(i/RATE) for i in range(RATE)],True))
    impact=[(rng.uniform(-1,1)*.5+math.sin(TAU*(160*t-70*t*t)))*math.exp(-t*17) for t in (i/RATE for i in range(12000))]
    report.append(write('Impact',impact))
    (ROOT/'Docs/Audio/ARCADE_AUDIO_AUDIT.json').write_text(json.dumps({'sampleRate':RATE,'format':'16-bit mono PCM','authorship':'Original procedural effects generated by this script; no sampled music or voices.','humanListeningApproved':False,'clips':report},indent=2))
